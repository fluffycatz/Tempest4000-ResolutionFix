# CLI
# ---------------------------------------------------------------------------
def main(argv):
    flags = {a for a in argv if a.startswith('--')}
    args = [a for a in argv if not a.startswith('--')]
    if '--help' in flags or '-h' in argv:
        print(__doc__); return 0
    if '--version' in flags:
        print(__version__); return 0

    if '--set-mode' in flags:
        i = argv.index('--set-mode')
        spec = argv[i+1] if i + 1 < len(argv) else ''
        rest = [a for a in args if a != spec]
        p = rest[0] if rest else default_prefs_path()
        if not p:
            print("prefs file not found - launch the game once first, or pass its path"); return 1
        set_mode(p, spec); return 0

    if '--gen-table' in flags:
        for path in args:
            data = open(path, 'rb').read()
            R = locate_sites(path)
            tbl = build_patch_table(R, cave=True)
            print("    %r: (%r, [" % (sha256(data), os.path.basename(path)))
            for off, old, new in tbl:
                print("        (0x%x, %r, %r)," % (off, old.hex(), new.hex()))
            print("    ]),")
        return 0

    exes = args or find_game_exes()
    if not exes:
        print("Tempest4000.exe not found. Pass its path, e.g.\n"
              '  "C:\\Program Files (x86)\\Steam\\steamapps\\common\\Tempest 4000\\Win10\\Tempest4000.exe"')
        return 1
    rc = 0
    for path in exes:
        print("== %s" % path)
        try:
            if '--restore' in flags:
                bak = path + '.orig'
                if not os.path.exists(bak):
                    print("   no backup found (%s). Use Steam > Verify integrity of game files." % bak); rc = 1; continue
                shutil.copy2(bak, path); print("   restored from", bak); continue
            data = bytearray(open(path, 'rb').read())
            label, table = table_for_file(path, data, want_cave='--no-cave' not in flags, force='--force' in flags)
            state = table_state(data, table)
            print("   build: %s   state: %s" % (label, state))
            if '--check' in flags:
                continue
            if all(row_state(data, r) == 'patched' for r in table):
                print("   already patched - nothing to do"); continue
            bak = path + '.orig'
            if not os.path.exists(bak):
                shutil.copy2(path, bak); print("   backup:", bak)
            n = apply_table(data, table)
            open(path, 'wb').write(data)
            print("   patched (%d bytes changed). sha256: %s" % (n, sha256(data)))
        except PermissionError:
            print("   permission denied - run from an elevated prompt or check the folder is writable"); rc = 1
        except LookupError as e:
            print("   %s" % e); rc = 1
    return rc

