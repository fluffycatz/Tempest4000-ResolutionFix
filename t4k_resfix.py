# Locating the game
# ---------------------------------------------------------------------------
def steam_libraries():
    roots = []
    if sys.platform == 'win32':
        try:
            import winreg
            for hive, key in ((winreg.HKEY_CURRENT_USER, r'Software\Valve\Steam'),
                              (winreg.HKEY_LOCAL_MACHINE, r'SOFTWARE\WOW6432Node\Valve\Steam')):
                try:
                    with winreg.OpenKey(hive, key) as k:
                        v = winreg.QueryValueEx(k, 'SteamPath' if hive == winreg.HKEY_CURRENT_USER else 'InstallPath')[0]
                        roots.append(v.replace('/', '\\'))
                except OSError:
                    pass
        except ImportError:
            pass
        roots += [r'C:\Program Files (x86)\Steam', r'C:\Program Files\Steam']
    else:
        home = os.path.expanduser('~')
        roots += [os.path.join(home, '.steam', 'steam'), os.path.join(home, '.local', 'share', 'Steam'),
                  os.path.join(home, '.var', 'app', 'com.valvesoftware.Steam', '.local', 'share', 'Steam')]
    libs = []
    for r in roots:
        if not os.path.isdir(r):
            continue
        libs.append(r)
        vdf = os.path.join(r, 'steamapps', 'libraryfolders.vdf')
        if os.path.exists(vdf):
            for m in re.finditer(r'"path"\s+"([^"]+)"', open(vdf, encoding='utf-8', errors='replace').read()):
                libs.append(m.group(1).replace('\\\\', '\\'))
    seen, out = set(), []
    for l in libs:
        n = os.path.normcase(os.path.normpath(l))
        if n not in seen and os.path.isdir(l):
            seen.add(n); out.append(l)
    return out

def find_game_exes():
    found = []
    for lib in steam_libraries():
        for sub in ('Win10', 'Win7-8'):
            p = os.path.join(lib, 'steamapps', 'common', 'Tempest 4000', sub, 'Tempest4000.exe')
            if os.path.exists(p):
                found.append(p)
    return found

